String localizeUi(String text, String languageCode) {
  if (languageCode == 'tr') return text;
  final reviewed = uiOverrides[text]?[languageCode];
  if (reviewed != null) return reviewed;
  final generated = uiTranslations[text]?[languageCode];
  if (generated != null) return generated;
  final games = RegExp(r'^(\d+) oyun$').firstMatch(text);
  if (games != null) {
    return languageCode == 'es'
        ? '${games[1]} partidas'
        : '${games[1]} games';
  }
  final points = RegExp(r'^(\d+) puan$').firstMatch(text);
  if (points != null) {
    return languageCode == 'es'
        ? '${points[1]} puntos'
        : '${points[1]} points';
  }
  final streak = RegExp(r'^6 bilişsel alan • günlük seri: (\d+)$')
      .firstMatch(text);
  if (streak != null) {
    return languageCode == 'es'
        ? 'Desafío diario • racha: ${streak[1]}'
        : 'Daily challenge • streak: ${streak[1]}';
  }
  final accuracy = RegExp(r'^(\d+)% bilişsel doğruluk$').firstMatch(text);
  if (accuracy != null) {
    return languageCode == 'es'
        ? '${accuracy[1]} % de aciertos'
        : '${accuracy[1]}% accuracy';
  }
  final dailyStreak = RegExp(r'^(\d+) günlük seri$').firstMatch(text);
  if (dailyStreak != null) {
    return languageCode == 'es'
        ? '${dailyStreak[1]} días seguidos'
        : '${dailyStreak[1]}-day streak';
  }
  final decisions = RegExp(r'^(\d+) karar üzerinden hesaplandı\.$')
      .firstMatch(text);
  if (decisions != null) {
    return languageCode == 'es'
        ? 'Basado en ${decisions[1]} respuestas.'
        : 'Based on ${decisions[1]} answers.';
  }
  final winner = RegExp(r'^(.+) kazandı!$').firstMatch(text);
  if (winner != null) {
    return languageCode == 'es'
        ? '¡Ganó ${winner[1]}!'
        : '${winner[1]} wins!';
  }
  final humanShare = RegExp(r'^(\d+)% İnsan$').firstMatch(text);
  if (humanShare != null) {
    return languageCode == 'es'
        ? '${humanShare[1]} % humano'
        : '${humanShare[1]}% human';
  }
  final freeAnswers =
      RegExp(r'^(\d+) Bedava Cevap Hakkın Var 🎁$').firstMatch(text);
  if (freeAnswers != null) {
    return languageCode == 'es'
        ? '${freeAnswers[1]} pistas disponibles 🎁'
        : '${freeAnswers[1]} hints available 🎁';
  }
  final categoryResult = RegExp(r'^(\d+)/(\d+) doğru • (.+)$')
      .firstMatch(text);
  if (categoryResult != null) {
    final comment = uiOverrides[categoryResult[3]]?[languageCode] ?? categoryResult[3]!;
    return languageCode == 'es'
        ? '${categoryResult[1]}/${categoryResult[2]} correctas • $comment'
        : '${categoryResult[1]}/${categoryResult[2]} correct • $comment';
  }
  // Category names can appear inside a score or icon label.
  var result = text;
  for (final label in const [
    'Davranışsal Ekonomi',
    'Bilişsel Yanılgılar',
    'Etik Paradokslar',
    'Stratejik Düşünce',
    'Bayesyen Mantık',
    'Oyun Teorisi',
  ]) {
    result = result.replaceAll(
      label,
      uiOverrides[label]?[languageCode] ?? label,
    );
  }
  return result;
}
